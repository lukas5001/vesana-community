def normalize_lang(value: str | None) -> str:
    return value if value in LANGUAGES else DEFAULT_LANG


def translate(lang: str, key: str, **kwargs) -> str:
    lang = normalize_lang(lang)
    text = TRANSLATIONS.get(lang, {}).get(key)
    if text is None:
        text = TRANSLATIONS[DEFAULT_LANG].get(key, key)
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, IndexError, ValueError):
            return text
    return text


def label(lang: str, prefix: str, value: str | None) -> str:
    """Translate an enum-ish value (``cat.server`` → „Server") or fall back to it.

    Categories/sort keys/filters come from the database or the service layer as
    English slugs; where no translation exists the slug itself is shown rather
    than a dotted key.
    """
    if not value:
        return "—"
    lang = normalize_lang(lang)
    key = f"{prefix}.{value}"
    text = TRANSLATIONS.get(lang, {}).get(key) or TRANSLATIONS[DEFAULT_LANG].get(key)
    return text if text is not None else value
